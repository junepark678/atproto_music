// The Node static web server (ADR 0005 §3.7; N1-06): web/dist in memory, the
// `_headers` rules of scripts/gen-config.ts, SHA-256 ETags with 304, the
// /index.html redirect, 405 with the JSON envelope, and the oracle's safe_path
// refusal (crates/server/src/http/assets.rs) applied to the raw request target.

import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { connect } from 'node:net';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { seededRandom } from '@atmusic/core/test-support/random';
import { afterEach, describe, expect, it } from 'vitest';
import { UUID_PATTERN } from '../../src/http/request-id';
import { type BridgeServer, createServer } from '../../src/node/http-bridge';
import { loadStaticAssets, type StaticFs } from '../../src/node/static-assets';

const ORIGIN = 'https://music.example.test';

// The values scripts/gen-config.ts writes (buildHeaders, ADR 0004 §8).
const CSP =
  "default-src 'self'; script-src 'self'; connect-src 'self' https:; img-src 'self' data:; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; require-trusted-types-for 'script'";
const HEADERS_FILE = `# Generated by scripts/gen-config.ts (ADR 0004 §8). Do not edit.
/*
  Content-Security-Policy: ${CSP}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
/assets/*
  Cache-Control: public, max-age=31536000, immutable
/
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/oauth/client-metadata.json
  Cache-Control: no-cache
`;

const INDEX = '<!doctype html><title>atmusic</title><script type="module" src="/assets/app-3f2a.js"></script>';
const APP_JS = 'console.log("atmusic");';
const SECRET = 'outside-dist-secret-7d1c';

const roots: string[] = [];
const servers: BridgeServer[] = [];
afterEach(async () => {
  for (const server of servers.splice(0)) await server.close();
  for (const dir of roots.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** A temporary root holding dist/ and, beside it, a secret file and directory outside dist. */
function makeDist(): { root: string; dist: string } {
  const root = mkdtempSync(join(tmpdir(), 'atmusic-static-'));
  roots.push(root);
  const dist = join(root, 'dist');
  mkdirSync(join(dist, 'assets'), { recursive: true });
  mkdirSync(join(dist, 'oauth'));
  writeFileSync(join(dist, 'index.html'), INDEX);
  writeFileSync(join(dist, 'assets', 'app-3f2a.js'), APP_JS);
  writeFileSync(join(dist, 'assets', 'app-3f2a.css'), 'body{margin:0}');
  writeFileSync(join(dist, 'assets', 'logo.svg'), '<svg xmlns="http://www.w3.org/2000/svg"/>');
  writeFileSync(join(dist, 'assets', 'blob.bin'), new Uint8Array([0, 1, 2]));
  writeFileSync(join(dist, 'oauth', 'client-metadata.json'), '{"client_id":"x"}');
  writeFileSync(join(dist, 'robots.txt'), 'User-agent: *\n');
  writeFileSync(join(dist, '_headers'), HEADERS_FILE);
  writeFileSync(join(root, 'secret.txt'), SECRET);
  mkdirSync(join(root, 'private'));
  writeFileSync(join(root, 'private', 'key.txt'), SECRET);
  // A link inside dist pointing outside it: never followed.
  symlinkSync(join(root, 'secret.txt'), join(dist, 'leak.txt'));
  symlinkSync(join(root, 'private'), join(dist, 'linked-dir'));
  return { root, dist };
}

/** node:fs with every path the loader touches recorded. */
function recordingFs(): StaticFs & { paths: string[] } {
  const paths: string[] = [];
  return {
    paths,
    readdirSync(path) {
      paths.push(resolve(path));
      return fs.readdirSync(path);
    },
    lstatSync(path) {
      paths.push(resolve(path));
      return fs.lstatSync(path);
    },
    readFileSync(path) {
      paths.push(resolve(path));
      return fs.readFileSync(path);
    },
  };
}

const sha256 = (text: string) => `"${createHash('sha256').update(text).digest('hex')}"`;
const get = (path: string, init: RequestInit = {}) => new Request(`${ORIGIN}${path}`, init);

/** Sends raw request bytes to the bridge and resolves with the raw response text. */
function rawRequest(port: number, bytes: string): Promise<string> {
  return new Promise((resolvePromise, reject) => {
    const socket = connect({ host: '127.0.0.1', port }, () => socket.end(bytes, 'latin1'));
    let text = '';
    socket.setEncoding('latin1');
    socket.on('data', (chunk: string) => {
      text += chunk;
    });
    socket.on('end', () => resolvePromise(text));
    socket.on('error', reject);
  });
}

describe('static assets', () => {
  it('files are served with the _headers CSP, nosniff, immutable /assets/* and no-cache /, an ETag, and 304 on If-None-Match', async () => {
    const { dist } = makeDist();
    const assets = loadStaticAssets(dist, { random: seededRandom(3) });
    expect(assets.paths).toEqual([
      '/assets/app-3f2a.css',
      '/assets/app-3f2a.js',
      '/assets/blob.bin',
      '/assets/logo.svg',
      '/index.html',
      '/oauth/client-metadata.json',
      '/robots.txt',
    ]);

    // `/` is index.html, no-cache, with every site-wide header.
    const root = assets.serve(get('/'))!;
    expect(root.status).toBe(200);
    expect(await root.text()).toBe(INDEX);
    expect(root.headers.get('content-type')).toBe('text/html; charset=utf-8');
    expect(root.headers.get('content-security-policy')).toBe(CSP);
    expect(root.headers.get('x-content-type-options')).toBe('nosniff');
    expect(root.headers.get('referrer-policy')).toBe('no-referrer');
    expect(root.headers.get('cache-control')).toBe('no-cache');
    expect(root.headers.get('etag')).toBe(sha256(INDEX));
    expect(root.headers.get('content-length')).toBe(String(INDEX.length));

    // A hashed asset: immutable, and the /* headers too; never joined with another Cache-Control.
    const js = assets.serve(get('/assets/app-3f2a.js'))!;
    expect(js.status).toBe(200);
    expect(await js.text()).toBe(APP_JS);
    expect(js.headers.get('content-type')).toBe('text/javascript; charset=utf-8');
    expect(js.headers.get('cache-control')).toBe('public, max-age=31536000, immutable');
    expect(js.headers.get('content-security-policy')).toBe(CSP);
    expect(js.headers.get('x-content-type-options')).toBe('nosniff');
    expect(js.headers.get('etag')).toBe(sha256(APP_JS));

    // The MIME table, with octet-stream (and nosniff) for an unknown extension.
    const types = Object.fromEntries(
      [
        '/assets/app-3f2a.css',
        '/assets/logo.svg',
        '/assets/blob.bin',
        '/robots.txt',
        '/oauth/client-metadata.json',
      ].map((p) => [p, assets.serve(get(p))!.headers.get('content-type')]),
    );
    expect(types).toEqual({
      '/assets/app-3f2a.css': 'text/css; charset=utf-8',
      '/assets/logo.svg': 'image/svg+xml',
      '/assets/blob.bin': 'application/octet-stream',
      '/robots.txt': 'text/plain; charset=utf-8',
      '/oauth/client-metadata.json': 'application/json',
    });
    // A file no specific rule covers gets only the /* headers.
    const robots = assets.serve(get('/robots.txt'))!;
    expect(robots.headers.get('cache-control')).toBeNull();
    expect(robots.headers.get('x-content-type-options')).toBe('nosniff');
    expect(assets.serve(get('/oauth/client-metadata.json'))!.headers.get('cache-control')).toBe('no-cache');

    // If-None-Match with the ETag (also weak, also in a list, also `*`): 304, no body, ETag and cache headers kept.
    for (const tag of [sha256(APP_JS), `W/${sha256(APP_JS)}`, `"other", ${sha256(APP_JS)}`, '*']) {
      const revalidated = assets.serve(get('/assets/app-3f2a.js', { headers: { 'if-none-match': tag } }))!;
      expect(revalidated.status, tag).toBe(304);
      expect(revalidated.body, tag).toBeNull();
      expect(revalidated.headers.get('etag')).toBe(sha256(APP_JS));
      expect(revalidated.headers.get('cache-control')).toBe('public, max-age=31536000, immutable');
    }
    const stale = assets.serve(get('/assets/app-3f2a.js', { headers: { 'if-none-match': sha256(INDEX) } }))!;
    expect(stale.status).toBe(200);
    expect(await stale.text()).toBe(APP_JS);

    // HEAD: the same headers, no body.
    const head = assets.serve(get('/', { method: 'HEAD' }))!;
    expect(head.status).toBe(200);
    expect(head.body).toBeNull();
    expect(head.headers.get('content-length')).toBe(String(INDEX.length));
    expect(head.headers.get('cache-control')).toBe('no-cache');

    // A path that is not a file is left to the dispatcher's assetMiss.
    expect(assets.serve(get('/feed'))).toBeNull();
    expect(assets.serve(get('/assets/missing.js'))).toBeNull();
    expect(assets.serve(get('/assets/'))).toBeNull();

    // Through the HTTP bridge on 127.0.0.1:0, the same bytes reach the client.
    const bridge = createServer({
      publicOrigin: ORIGIN,
      listen: { host: '127.0.0.1', port: 0 },
      handler: (request, info) => assets.serve(request, info.rawTarget) ?? new Response('miss', { status: 404 }),
    });
    servers.push(bridge);
    const { port, authority } = await bridge.start();
    const wire = await rawRequest(
      port,
      `GET /assets/app-3f2a.js HTTP/1.1\r\nHost: ${authority}\r\nIf-None-Match: ${sha256(APP_JS)}\r\nConnection: close\r\n\r\n`,
    );
    expect(wire).toMatch(/^HTTP\/1\.1 304 /);
    expect(wire.toLowerCase()).toContain(`etag: ${sha256(APP_JS)}`);
    expect(wire.split('\r\n\r\n')[1]).toBe('');
  });

  it('/index.html redirects to /, /_headers is 404, and POST to an existing file is 405 with Allow: GET, HEAD and the JSON envelope', async () => {
    const { dist } = makeDist();
    const assets = loadStaticAssets(dist, { random: seededRandom(4) });

    const redirect = assets.serve(get('/index.html'))!;
    expect(redirect.status).toBe(301);
    expect(redirect.headers.get('location')).toBe('/');
    expect(assets.serve(get('/index.html?from=x&y=1'))!.headers.get('location')).toBe('/?from=x&y=1');

    for (const method of ['GET', 'HEAD', 'POST']) {
      const hidden = assets.serve(get('/_headers', { method }))!;
      expect(hidden.status, method).toBe(404);
      expect(hidden.headers.get('content-type')).toBe('application/json');
      const body = await hidden.text();
      expect(body).not.toContain('Content-Security-Policy');
      expect(JSON.parse(body)).toEqual({
        error: {
          code: 'not_found',
          message: 'The resource is absent or inactive.',
          requestId: hidden.headers.get('x-request-id'),
        },
      });
    }
    expect(assets.has('/_headers')).toBe(false);

    for (const [method, path] of [
      ['POST', '/'],
      ['POST', '/assets/app-3f2a.js'],
      ['PUT', '/index.html'],
      ['DELETE', '/robots.txt'],
    ] as const) {
      const refused = assets.serve(get(path, { method, body: method === 'DELETE' ? undefined : 'x' }))!;
      expect(refused.status, `${method} ${path}`).toBe(405);
      expect(refused.headers.get('allow')).toBe('GET, HEAD');
      expect(refused.headers.get('content-type')).toBe('application/json');
      expect(refused.headers.get('cache-control')).toBe('no-store');
      const envelope = (await refused.json()) as { error: { code: string; message: string; requestId: string } };
      expect(envelope).toEqual({
        error: {
          code: 'method_not_allowed',
          message: 'The method is not allowed for this resource.',
          requestId: refused.headers.get('x-request-id'),
        },
      });
      expect(envelope.error.requestId).toMatch(UUID_PATTERN);
    }
    // A POST to a path that is not a file is not the static server's to refuse.
    expect(assets.serve(get('/api/v1/notify', { method: 'POST', body: '{}' }))).toBeNull();
  });

  it('%2e%2e, backslash and NUL paths are refused without touching the filesystem outside dist', async () => {
    const { root, dist } = makeDist();
    const recorder = recordingFs();
    const assets = loadStaticAssets(dist, { random: seededRandom(5), fs: recorder });

    // Loading touched only dist and what is inside it; links were seen (lstat) but never followed.
    const distRoot = resolve(dist);
    expect(recorder.paths.length).toBeGreaterThan(0);
    for (const path of recorder.paths) {
      expect(path === distRoot || path.startsWith(distRoot + sep), path).toBe(true);
    }
    const readFiles = recorder.paths.filter((p) => p.endsWith('leak.txt') || p.includes('linked-dir'));
    expect(new Set(readFiles)).toEqual(new Set([join(distRoot, 'leak.txt'), join(distRoot, 'linked-dir')]));
    expect(assets.has('/leak.txt')).toBe(false);
    expect(assets.has('/linked-dir/key.txt')).toBe(false);
    const touchedAtLoad = recorder.paths.length;

    const refused = [
      '/%2e%2e/secret.txt',
      '/assets/%2E%2E/%2e%2e/secret.txt',
      '/assets/%2e%2e%2fsecret.txt',
      '/..%5csecret.txt',
      '/assets\\..\\..\\secret.txt',
      '/%5c..%5csecret.txt',
      '/index.html%00',
      '/%00/../secret.txt',
      '/assets/app-3f2a.js%00.html',
      '/./index.html',
      '/assets/../index.html',
      '/%25%32%65%25%32%65/secret.txt',
      '/%ff%fe',
      '/%2',
    ];
    for (const raw of refused) {
      // The request URL as WHATWG URL would resolve it, and the raw target the bridge saw.
      const response = assets.serve(get('/'), raw)!;
      expect(response, raw).not.toBeNull();
      expect(response.status, raw).toBe(404);
      const text = await response.text();
      expect(text, raw).not.toContain(SECRET);
      expect(JSON.parse(text).error.code, raw).toBe('not_found');
    }
    // A link target outside dist is never served, under its link name either.
    expect(assets.serve(get('/leak.txt'))).toBeNull();
    expect(assets.serve(get('/linked-dir/key.txt'))).toBeNull();
    // Serving reads nothing at all: the files are in memory.
    expect(recorder.paths.length).toBe(touchedAtLoad);

    // Over the wire through the bridge, with the raw request target.
    const bridge = createServer({
      publicOrigin: ORIGIN,
      listen: { host: '127.0.0.1', port: 0 },
      handler: (request, info) => assets.serve(request, info.rawTarget) ?? new Response('miss', { status: 404 }),
    });
    servers.push(bridge);
    const { port, authority } = await bridge.start();
    for (const target of ['/%2e%2e/secret.txt', '/assets/%2e%2e/%2e%2e/private/key.txt', '/..%5csecret.txt', '/%00']) {
      const wire = await rawRequest(port, `GET ${target} HTTP/1.1\r\nHost: ${authority}\r\nConnection: close\r\n\r\n`);
      expect(wire, target).toMatch(/^HTTP\/1\.1 404 /);
      expect(wire, target).toContain('"code":"not_found"');
      expect(wire, target).not.toContain(SECRET);
    }
    expect(recorder.paths.length).toBe(touchedAtLoad);
    // The secret files are still there: refusal, not absence, kept them out.
    expect(fs.readFileSync(join(root, 'secret.txt'), 'utf8')).toBe(SECRET);
  });
});
