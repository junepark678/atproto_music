  it('/health/ready is 503 when the database is not writable or the OAuth keyset failed to load', async () => {
    // A Db whose writes fail like SQLITE_READONLY while `readOnly` is set (fault injection through the Db interface).
    let readOnly = false;
    const writes: string[] = [];
    const wrap = (db: Db): Db => ({
      all: (sql, ...p) => db.all(sql, ...p),
      one: (sql, ...p) => db.one(sql, ...p),
      tx: (fn) => db.tx(fn),
      run: (sql, ...p) => {
        writes.push(sql.trim().split(/\s+/)[0] as string);
        if (readOnly) throw Object.assign(new Error('attempt to write a readonly database'), { errcode: 8 });
        return db.run(sql, ...p);
      },
    });
    const app = await startApp({ wrapDb: wrap });

    const ok = await app.fetch('/health/ready');
    expect(ok.status).toBe(200);
    expect(await jsonOf(ok)).toEqual({ status: 'ready' });
    // The probe wrote and was rolled back: no probe row is left behind.
    expect(writes).toContain('INSERT');
    expect(app.db.all('SELECT * FROM counters WHERE name = ?', WRITE_PROBE_COUNTER)).toEqual([]);

    readOnly = true;
    const failed = await app.fetch('/health/ready');
    expect(failed.status).toBe(503);
    expect(await jsonOf(failed)).toEqual({
      error: {
        code: 'not_ready',
        message: 'Index storage is not initialized.',
        requestId: failed.headers.get('x-request-id'),
      },
    });
    const report = await app.composed.ready();
    expect(report.ready).toBe(false);
    expect(report.checks).toEqual({ schema: true, config: true, secrets: true, oauthKeyset: true, dbWrite: false });
    expect(report.failures).toEqual(['dbWrite']);
    expect(app.log.logs.filter((l) => l.event === 'ready.not_ready').map((l) => l.failures)).toEqual([['dbWrite']]);
    // Liveness is the process only.
    expect((await app.fetch('/health/live')).status).toBe(200);

    readOnly = false;
    expect((await app.fetch('/health/ready')).status).toBe(200);
    await app.close();

    // An OAuth signing key whose public half is another key's: the keyset fails to load.
    const good = testSecrets();
    const other = testJwk('k2', 'another key');
    const badKeyset: Secrets = {
      cursorKey: good.cursorKey,
      encryptionKeys: good.encryptionKeys,
      oauthSigningKeys: [
        { ...(good.oauthSigningKeys[0] as Secrets['oauthSigningKeys'][number]), x: other.x, y: other.y },
      ],
      oauthAnnouncedKeys: [],
      lastfm: null,
    };
    const broken = await startApp({ secrets: badKeyset });
    const res = await broken.fetch('/health/ready');
    expect(res.status).toBe(503);
    expect(((await jsonOf(res)) as { error: { code: string } }).error.code).toBe('not_ready');
    const brokenReport = await broken.composed.ready();
    expect(brokenReport.checks).toEqual({
      schema: true,
      config: true,
      secrets: true,
      oauthKeyset: false,
      dbWrite: true,
    });
    expect(brokenReport.failures).toEqual(['oauthKeyset']);
    const keysetLines = broken.log.logs.filter((l) => l.event === 'oauth.keyset_invalid');
    expect(keysetLines).toHaveLength(1);
    expect(keysetLines[0]?.kid).toBe('k1');
    // The private scalar never reaches a log line.
    expect(broken.log.lines.join('\n')).not.toContain(good.oauthSigningKeys[0]?.d as string);
    expect((await broken.fetch('/health/live')).status).toBe(200);

    // Warnings do not change the status: low_disk is reported with a 200.
    const lowDisk = await startApp({ diskLow: () => true });
    const warned = await lowDisk.fetch('/health/ready');
    expect(warned.status).toBe(200);
    const warnedBody = await jsonOf(warned);
    expect(warnedBody).toEqual({ status: 'ready', warnings: ['low_disk'] });
    expect(checkResponse('GET', '/health/ready', { status: 200, headers: warned.headers, body: warnedBody })).toBe(
      'valid',
    );
    // A feature's warning (oauth_store_degraded, N2-03) is merged the same way,
    // deduplicated, and still matches the contract's Ready schema.
    const degraded = await startApp({
      diskLow: () => true,
      features: [
        { name: 'oauth-store', readiness: () => ({ warnings: ['oauth_store_degraded', 'low_disk'] }) },
        { name: 'other', readiness: () => ({ warnings: ['oauth_store_degraded'] }) },
      ],
    });
    const degradedRes = await degraded.fetch('/health/ready');
    const degradedBody = await jsonOf(degradedRes);
    expect(degradedRes.status).toBe(200);
    expect(degradedBody).toEqual({ status: 'ready', warnings: ['low_disk', 'oauth_store_degraded'] });
    expect(
      checkResponse('GET', '/health/ready', { status: 200, headers: degradedRes.headers, body: degradedBody }),
    ).toBe('valid');
    // The contract's warnings enum is closed: a value outside it fails the schema,
    // so compose logs an unknown feature warning and never returns it.
    expect(
      checkResponse('GET', '/health/ready', {
        status: 200,
        headers: degradedRes.headers,
        body: { status: 'ready', warnings: ['disk_on_fire'] },
      }),
    ).not.toBe('valid');
    const unknown = await startApp({
      features: [{ name: 'rogue', readiness: () => ({ warnings: ['disk_on_fire' as ReadinessWarning] }) }],
    });
    const unknownRes = await unknown.fetch('/health/ready');
    const unknownBody = await jsonOf(unknownRes);
    expect(unknownRes.status).toBe(200);
    expect(unknownBody).toEqual({ status: 'ready' });
    expect(checkResponse('GET', '/health/ready', { status: 200, headers: unknownRes.headers, body: unknownBody })).toBe(
      'valid',
    );
    expect(unknown.log.logs.filter((l) => l.event === 'ready.unknown_warning').map((l) => l.feature)).toEqual([
      'rogue',
    ]);
  });

  it("every ctx built by compose carries deps, app and peer, and need(ctx, 'app') on a ctx without app answers 500 CtxWiringError", async () => {
    const seen: RequestCtx[] = [];
    const record: RouteDef['handler'] = async (_req, ctx) => {
      seen.push(ctx);
      const app = need(ctx, 'app') as unknown as Record<string, unknown>;
      return new Response(JSON.stringify({ service: (app.probe as { id: string }).id }), {
        headers: { 'content-type': 'application/json' },
      });
    };
    const probe = { id: 'probe-service' };
    const routes: RouteDef[] = [
      { method: 'GET', pattern: '/api/v1/test/ctx', handler: record },
      { method: 'POST', pattern: '/api/v1/test/ctx', handler: record },
      { method: 'GET', pattern: '/2.0/', handler: record },
      { method: 'GET', pattern: '/1/test/{name}', handler: record },
    ];
    const app = await startApp({
      routes,
      features: [{ name: 'probe', services: () => ({ probe }) as never }],
    });

    const answers = [
      await app.fetch('/api/v1/test/ctx'),
      await app.fetch('/api/v1/test/ctx', { method: 'POST', body: '{}' }),
      await app.fetch('/2.0/?method=user.getInfo'),
      await app.fetch('/1/test/abc'),
    ];
    for (const res of answers) {
      expect(res.status).toBe(200);
      expect(await jsonOf(res)).toEqual({ service: 'probe-service' });
    }
    expect(seen).toHaveLength(4);
    seen.forEach((ctx, i) => {
      expect(ctx.deps).toBe(app.composed.core.deps);
      expect(ctx.app).toBe(app.composed.app);
      expect((ctx.app as unknown as Record<string, unknown>).probe).toBe(probe);
      expect(ctx.peer).toBe('127.0.0.1');
      expect(ctx.clientIp).toBe('127.0.0.1');
      expect(ctx.index).toBe(app.composed.core);
      expect(ctx.env).toEqual({ LEXICON_PREFIX: 'com.example.atmusic', NAMESPACE_OWNERSHIP_REF: '' });
      expect(ctx.requestId).toBe(answers[i]?.headers.get('x-request-id'));
      expect(ctx.cursorKey.algorithm.name).toBe('HMAC');
      expect(need(ctx, 'deps')).toBe(app.composed.core.deps);
      expect(need(ctx, 'peer')).toBe('127.0.0.1');
    });
    expect(new Set(seen.map((c) => c.requestId)).size).toBe(4);

    // A context without `app` (a composition that did not wire it): need() throws CtxWiringError...
    const bare: RequestCtx = { ...(seen[0] as RequestCtx) };
    delete bare.app;
    expect(() => need(bare, 'app')).toThrow(CtxWiringError);
    try {
      need(bare, 'app');
    } catch (error) {
      expect((error as CtxWiringError).key).toBe('app');
      expect((error as Error).name).toBe('CtxWiringError');
    }
    // ...which the dispatcher answers as the generic 500, logged by error name only.
    const lines: Array<Record<string, unknown>> = [];
    const dispatch = createDispatcher({
      routes,
      assets: null,
      context: (_request, _info, requestId) => ({ ...bare, requestId }),
      log: { log: (level, event, fields) => lines.push({ level, event, ...fields }) },
      random: seededRandom(3),
    });
    const before = seen.length;
    const res = await dispatch(new Request('https://music.example.test/api/v1/test/ctx'), { peer: '127.0.0.1' });
    expect(res.status).toBe(500);
    const requestId = res.headers.get('x-request-id');
    expect(requestId).toMatch(UUID_PATTERN);
    expect(await jsonOf(res)).toEqual({
      error: { code: 'internal_error', message: 'An internal error occurred.', requestId },
    });
    expect(seen.length).toBe(before + 1);
    expect(lines.filter((l) => l.event === 'request.failed')).toEqual([
      {
        level: 'error',
        event: 'request.failed',
        requestId,
        method: 'GET',
        route: '/api/v1/test/ctx',
        status: 500,
        error: 'CtxWiringError',
      },
    ]);
  });

