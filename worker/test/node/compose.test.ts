async function jsonOf(res: Response): Promise<unknown> {
  return JSON.parse(await res.text());
}

function notFoundBody(requestId: string | null) {
  return {
    error: { code: 'not_found', message: 'The resource is absent or inactive.', requestId },
  };
}

